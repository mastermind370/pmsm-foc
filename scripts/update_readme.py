"""Fill the measured-results blocks of README.md from results/*.md and results/*.json.

No number in the README is typed by hand: the experiments and verification tables are copied from
the files the experiment and verification scripts wrote, together with where/how they were run.

Usage:
    python scripts/update_readme.py          # rewrite README.md in place
    python scripts/update_readme.py --check  # exit 1 if README.md is out of date (no changes)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MISSING = "_Not generated yet. Run `{cmd}`, then `python scripts/update_readme.py`._"


def _read(root: Path, name: str):
    p = root / "results" / name
    return p.read_text() if p.exists() else None


def _meta(root: Path, name: str) -> dict:
    p = root / "results" / name
    return json.loads(p.read_text()).get("meta", {}) if p.exists() else {}


def experiments_block(root: Path) -> str:
    md = _read(root, "metrics.md")
    if md is None:
        return MISSING.format(cmd="PYTHONPATH=src python scripts/run_experiments.py")
    m = _meta(root, "metrics.json")
    prov = (f"_Generated by `scripts/run_experiments.py` (commit `{m.get('git_commit') or 'unknown'}`, "
            f"Python {m.get('python', '?')}, {m.get('machine', '?')}, run time {m.get('wall_time_s', '?')} s). "
            f"Full data: `results/metrics.json`._")
    return md.rstrip() + "\n\n" + prov


def verification_block(root: Path) -> str:
    md = _read(root, "verification.md")
    if md is None:
        return MISSING.format(cmd="PYTHONPATH=src python scripts/verify_q15.py")
    m = _meta(root, "verification.json")
    where = m.get("cpu") or m.get("machine") or "?"
    prov = (f"_Generated by `scripts/verify_q15.py` (commit `{m.get('git_commit') or 'unknown'}`, {where}, "
            f"{m.get('compiler', '?')}, `{m.get('compile_flags', '?')}`, Python {m.get('python', '?')}). "
            f"Full data: `results/verification.json`._")
    return md.rstrip() + "\n\n" + prov


def _sub(doc: str, name: str, text: str) -> str:
    pat = re.compile(rf"(<!-- BEGIN:{name} -->)\n.*?\n(<!-- END:{name} -->)", re.S)
    if not pat.search(doc):
        raise SystemExit(f"README.md is missing the <!-- BEGIN:{name} --> / <!-- END:{name} --> markers")
    return pat.sub(lambda m: f"{m.group(1)}\n{text}\n{m.group(2)}", doc)


def render(doc: str, root: Path = ROOT) -> str:
    doc = _sub(doc, "experiments", experiments_block(root))
    return _sub(doc, "verification", verification_block(root))


def main(argv) -> int:
    readme = ROOT / "README.md"
    old = readme.read_text()
    new = render(old)
    if "--check" in argv:
        if new != old:
            print("README.md is out of date: run python scripts/update_readme.py")
            return 1
        print("README.md is up to date")
        return 0
    readme.write_text(new)
    print("README.md updated" if new != old else "README.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
